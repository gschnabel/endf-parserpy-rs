#[cfg(test)]
mod tests {
    use super::*;
    use crate::recipe::parse_recipe;

    #[test]
    fn test_compile_mf3_recipe() {
        let recipe_text = "\
[MAT, 3, MT/ ZA, AWR, 0, 0, 0, 0] HEAD
[MAT, 3, MT/ QM, QI, 0, LR, NR, NP / E / xs]TAB1 (xstable)
SEND
";
        let recipe = parse_recipe(recipe_text).unwrap();
        let code = compile_recipe(3, -1, &recipe);
        // Verify it contains key elements
        assert!(code.contains("read_cont"), "should call read_cont");
        assert!(code.contains("read_tab1"), "should call read_tab1");
        assert!(code.contains("xstable"), "should reference xstable section");
        assert!(code.contains("var_za"), "should have var_za");
        assert!(code.contains("var_awr"), "should have var_awr");
        assert!(code.contains("var_qm"), "should have var_qm");
        assert!(code.contains("var_qi"), "should have var_qi");
        assert!(code.contains("var_lr"), "should have var_lr");
    }

    #[test]
    fn test_compile_head_only() {
        let recipe_text = "[MAT, 3, MT/ ZA, AWR, 0, 0, 0, 0] HEAD\nSEND\n";
        let recipe = parse_recipe(recipe_text).unwrap();
        let code = compile_recipe(3, -1, &recipe);
        assert!(code.contains("let (cont, _ctrl) = read_cont"));
        assert!(code.contains("var_za = cont.c1;"));
        assert!(code.contains("var_awr = cont.c2;"));
    }

    #[test]
    fn test_compile_for_loop() {
        let recipe_text = "\
for i = 1 to NR:
[MAT, 3, MT/ C1, C2, L1, L2, N1, N2]CONT
endfor
";
        let recipe = parse_recipe(recipe_text).unwrap();
        let code = compile_recipe(3, -1, &recipe);
        assert!(code.contains("for var_i_loop_ in"));
        assert!(code.contains("var_nr"));
    }

    #[test]
    fn test_compile_if_clause() {
        let recipe_text = "\
if LFW == 0:
SEND
elif LFW == 1:
SEND
else:
SEND
endif
";
        let recipe = parse_recipe(recipe_text).unwrap();
        let code = compile_recipe(3, -1, &recipe);
        assert!(code.contains("if"));
        assert!(code.contains("else if"));
        assert!(code.contains("else"));
    }

    #[test]
    fn test_compile_section() {
        let recipe_text = "\
(mysection)
[MAT, 3, MT/ C1, C2, L1, L2, N1, N2]CONT
(/mysection)
";
        let recipe = parse_recipe(recipe_text).unwrap();
        let code = compile_recipe(3, -1, &recipe);
        assert!(code.contains("section_mysection"));
        assert!(code.contains("result.insert(\"mysection\""));
    }

    #[test]
    fn test_compile_abbreviation() {
        let recipe_text = "NW := 6*NRS + 1\n";
        let recipe = parse_recipe(recipe_text).unwrap();
        let code = compile_recipe(3, -1, &recipe);
        // Abbreviation should NOT generate a var_nw declaration or assignment.
        assert!(!code.contains("var_nw"), "abbreviation should not create a runtime variable");
        // The RHS variables should still be declared (they appear in collect_vars_expr).
        assert!(code.contains("var_nrs"), "RHS vars should still be declared");
    }

    #[test]
    fn test_compile_catalogue_dispatch() {
        let recipe_text = "[MAT, 3, MT/ ZA, AWR, 0, 0, 0, 0] HEAD\nSEND\n";
        let recipe = parse_recipe(recipe_text).unwrap();
        let code = compile_catalogue(&[(3, -1, &recipe)]);
        assert!(code.contains("pub fn parse_section("));
        assert!(code.contains("parse_mf3_wildcard"));
    }
}
