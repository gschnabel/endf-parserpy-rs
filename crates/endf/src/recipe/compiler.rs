/// Extract the variable name from a simple scalar variable expression.
fn is_zero(s: &str) -> bool { s == "0_f64" || s == "0.0" }
fn is_one(s: &str) -> bool { s == "1_f64" || s == "1.0" }
fn neg_str(a: &str) -> String { if is_zero(a) { "0_f64".into() } else { format!("-({})", a) } }
fn add_str(a: &str, b: &str) -> String { if is_zero(a) { b.into() } else if is_zero(b) { a.into() } else { format!("({} + {})", a, b) } }
fn sub_str(a: &str, b: &str) -> String { if is_zero(b) { a.into() } else if is_zero(a) { neg_str(b) } else { format!("({} - {})", a, b) } }
fn mul_str(a: &str, b: &str) -> String { if is_zero(a) || is_zero(b) { "0_f64".into() } else if is_one(a) { b.into() } else if is_one(b) { a.into() } else { format!("({} * {})", a, b) } }
fn div_str(a: &str, b: &str) -> String { if is_zero(a) { "0_f64".into() } else if is_one(b) { a.into() } else { format!("({} / ({}))", a, b) } }

fn get_simple_scalar_var(expr: &Expr) -> Option<String> {
    match expr {
        Expr::Variable(v) if v.indices.is_empty() => Some(v.name.clone()),
        Expr::InconsistentVar(v) if v.indices.is_empty() => Some(v.name.clone()),
        _ => None,
    }
}

// ---------------------------------------------------------------------------
// Variable collection – pre-pass to find all variable names in a recipe
// ---------------------------------------------------------------------------

/// Recursively walk the recipe AST and collect all variable names that appear
/// anywhere (fields, conditions, loop bounds, abbreviations, etc.).
/// Returns a set of lowercased variable names (matching the `var_xxx` naming).
fn collect_variables(recipe: &[RecipeNode]) -> HashSet<String> {
    let mut vars = HashSet::new();
    for node in recipe {
        collect_vars_node(node, &mut vars);
    }
    vars
}

fn collect_vars_node(node: &RecipeNode, vars: &mut HashSet<String>) {
    match node {
        RecipeNode::HeadOrCont { fields, .. } => {
            for f in fields {
                collect_vars_expr(f, vars);
            }
        }
        RecipeNode::Tab1 { fields, x_var, y_var, table_name, .. } => {
            for f in fields {
                collect_vars_expr(f, vars);
            }
            collect_vars_extvar(x_var, vars);
            collect_vars_extvar(y_var, vars);
            if let Some(tn) = table_name {
                collect_vars_extvar(tn, vars);
            }
        }
        RecipeNode::Tab2 { fields, z_var, table_name, .. } => {
            for f in fields {
                collect_vars_expr(f, vars);
            }
            collect_vars_extvar(z_var, vars);
            if let Some(tn) = table_name {
                collect_vars_extvar(tn, vars);
            }
        }
        RecipeNode::List { fields, body, list_name, .. } => {
            for f in fields {
                collect_vars_expr(f, vars);
            }
            collect_vars_list_body(body, vars);
            if let Some(ln) = list_name {
                collect_vars_extvar(ln, vars);
            }
        }
        RecipeNode::Dir { fields, .. } => {
            for f in fields {
                collect_vars_expr(f, vars);
            }
        }
        RecipeNode::Intg { fields, ndigit, .. } => {
            for f in fields {
                collect_vars_expr(f, vars);
            }
            collect_vars_expr(ndigit, vars);
        }
        RecipeNode::Text { placeholders, .. } => {
            for ph in placeholders {
                if let Some(ref v) = ph.var {
                    collect_vars_extvar(v, vars);
                }
            }
        }
        RecipeNode::ForLoop { var, start, stop, body } => {
            vars.insert(var.to_lowercase());
            collect_vars_expr(start, vars);
            collect_vars_expr(stop, vars);
            for n in body {
                collect_vars_node(n, vars);
            }
        }
        RecipeNode::RepeatLoop { var, body, until } => {
            if let Some((v, init)) = var {
                vars.insert(v.to_lowercase());
                collect_vars_expr(init, vars);
            }
            for n in body {
                collect_vars_node(n, vars);
            }
            collect_vars_bool(until, vars);
        }
        RecipeNode::IfClause { branches, else_body } => {
            for b in branches {
                collect_vars_bool(&b.condition, vars);
                if let Some(ref la) = b.lookahead {
                    collect_vars_expr(la, vars);
                }
                for n in &b.body {
                    collect_vars_node(n, vars);
                }
            }
            if let Some(eb) = else_body {
                for n in eb {
                    collect_vars_node(n, vars);
                }
            }
        }
        RecipeNode::Section { name, body } => {
            collect_vars_extvar(name, vars);
            for n in body {
                collect_vars_node(n, vars);
            }
        }
        RecipeNode::Abbreviation { name: _, expr } => {
            // Don't insert the abbreviation name itself — it's a compile-time
            // substitution, not a runtime variable. We still collect variables
            // from the RHS expression in case they appear nowhere else.
            collect_vars_expr(expr, vars);
        }
        RecipeNode::Send | RecipeNode::Stop { .. } | RecipeNode::Comment(_) => {}
    }
}

fn collect_vars_expr(expr: &Expr, vars: &mut HashSet<String>) {
    match expr {
        Expr::Variable(v) | Expr::InconsistentVar(v) => {
            collect_vars_extvar(v, vars);
        }
        Expr::Neg(a) | Expr::Bracket(a) => collect_vars_expr(a, vars),
        Expr::Add(a, b) | Expr::Sub(a, b) | Expr::Mul(a, b)
        | Expr::Div(a, b) | Expr::Mod(a, b) => {
            collect_vars_expr(a, vars);
            collect_vars_expr(b, vars);
        }
        Expr::Number(_) | Expr::DesiredNumber(_) => {}
    }
}

fn collect_vars_extvar(v: &ExtVarName, vars: &mut HashSet<String>) {
    vars.insert(v.name.to_lowercase());
    for idx in &v.indices {
        collect_vars_expr(idx, vars);
    }
}

fn collect_vars_bool(expr: &BoolExpr, vars: &mut HashSet<String>) {
    match expr {
        BoolExpr::Comparison { left, right, .. } => {
            collect_vars_expr(left, vars);
            collect_vars_expr(right, vars);
        }
        BoolExpr::And(a, b) | BoolExpr::Or(a, b) => {
            collect_vars_bool(a, vars);
            collect_vars_bool(b, vars);
        }
    }
}

fn collect_vars_list_body(items: &[ListItem], vars: &mut HashSet<String>) {
    for item in items {
        match item {
            ListItem::Value(expr) => collect_vars_expr(expr, vars),
            ListItem::Loop { body, var, start, stop } => {
                vars.insert(var.to_lowercase());
                collect_vars_expr(start, vars);
                collect_vars_expr(stop, vars);
                collect_vars_list_body(body, vars);
            }
            ListItem::Padding => {}
        }
    }
}

