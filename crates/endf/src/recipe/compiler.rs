fn generate_header() -> String {
    r#"//! Auto-generated ENDF parse functions. DO NOT EDIT.
//!
//! Generated by the endf-parser recipe compiler.

#![allow(unused_variables, unused_mut, unused_assignments)]

use endf::records::{self, read_cont, read_tab1, read_tab1_body, read_tab2, read_tab2_body, read_list, read_intg, read_endf_numbers};
use endf::records::{extract_cont_originals, write_cont_preserved, write_tab1_body_preserved, write_endf_values};
use endf::records::{write_cont, write_text, write_dir, write_intg, write_tab1_body, write_tab2_body, write_send, ContRecord, TextRecord, DirRecord, IntgRecord, Tab1Body, Tab2Body, CtrlRecord};
use endf::fortran::{fortstr_to_f64, read_fort_int, f64_to_fortstr};
use endf::value::{EndfKey, EndfValue};
use endf::options::{ReadOpts, ParseOpts, WriteOpts};
use endf::error::{EndfError, EndfResult};

/// Convert an f64 to EndfValue, using Int when the value is an exact integer.
#[inline]
fn f64_to_endf_value(v: f64) -> EndfValue {
    if v.is_finite() && v == (v as i64) as f64 {
        EndfValue::Int(v as i64)
    } else {
        EndfValue::Float(v)
    }
}

/// Build an EndfValue list from a slice of i64.
#[inline]
fn list_from_i64(vals: &[i64]) -> EndfValue {
    EndfValue::List(vals.iter().map(|v| Some(EndfValue::Int(*v))).collect())
}

/// Build an EndfValue list from a slice of f64.
/// All TAB1/LIST body values are floats by design — skip integer check.
#[inline]
fn list_from_f64(vals: &[f64]) -> EndfValue {
    EndfValue::List(vals.iter().map(|v| Some(EndfValue::Float(*v))).collect())
}

/// Read a float scalar from an EndfValue dict.
#[inline]
fn get_float(data: &EndfValue, key: &str) -> f64 {
    data.get(key).and_then(|v| v.as_float()).unwrap_or(0.0)
}

/// Read an integer scalar from an EndfValue dict.
#[inline]
fn get_int(data: &EndfValue, key: &str) -> i64 {
    data.get(key).and_then(|v| v.as_int()).unwrap_or(0)
}

/// Read a Vec<i64> from an EndfValue list.
#[inline]
fn get_int_vec(data: &EndfValue, key: &str) -> Vec<i64> {
    match data.get(key) {
        Some(EndfValue::List(l)) => l.iter()
            .map(|v| v.as_ref().and_then(|e| e.as_int()).unwrap_or(0))
            .collect(),
        _ => Vec::new(),
    }
}

/// Read a Vec<f64> from an EndfValue list.
#[inline]
fn get_float_vec(data: &EndfValue, key: &str) -> Vec<f64> {
    match data.get(key) {
        Some(EndfValue::List(l)) => l.iter()
            .map(|v| v.as_ref().and_then(|e| e.as_float()).unwrap_or(0.0))
            .collect(),
        _ => Vec::new(),
    }
}

/// Build a CtrlRecord from MAT/MF/MT in the data dict.
#[inline]
fn get_ctrl(data: &EndfValue) -> CtrlRecord {
    CtrlRecord {
        mat: get_int(data, "MAT") as i32,
        mf: get_int(data, "MF") as i32,
        mt: get_int(data, "MT") as i32,
    }
}

/// Like f64_to_endf_value but returns PreservedFloat when original is available.
#[inline]
fn f64_to_endf_value_preserved(v: f64, orig: Option<String>) -> EndfValue {
    match orig {
        Some(s) => EndfValue::PreservedFloat(v, s),
        None => f64_to_endf_value(v),
    }
}

/// Like list_from_f64 but produces PreservedFloat where originals are available.
fn list_from_f64_preserved(vals: &[f64], origs: &[Option<String>]) -> EndfValue {
    EndfValue::List(
        vals.iter()
            .zip(origs.iter())
            .map(|(&v, orig)| {
                Some(match orig {
                    Some(s) => EndfValue::PreservedFloat(v, s.clone()),
                    None => EndfValue::Float(v),
                })
            })
            .collect(),
    )
}

/// Read a float from data dict, returning the raw EndfValue for write preservation.
fn get_endf_value_or_zero(data: &EndfValue, key: &str) -> EndfValue {
    data.get(key).cloned().unwrap_or(EndfValue::Float(0.0))
}

/// Read a float vec from data dict as raw EndfValues for write preservation.
fn get_endf_value_vec<'a>(data: &'a EndfValue, key: &str) -> Vec<&'a EndfValue> {
    match data.get(key) {
        Some(EndfValue::List(l)) => l.iter()
            .filter_map(|v| v.as_ref())
            .collect(),
        _ => Vec::new(),
    }
}

/// Create an empty container for indexed variables, respecting array_type.
/// Dict mode creates an EndfValue::Dict; List mode creates an EndfValue::List.
#[inline]
fn make_container(parse_opts: &ParseOpts) -> EndfValue {
    match parse_opts.array_type {
        endf::options::ArrayType::Dict => EndfValue::new_dict(),
        endf::options::ArrayType::List => EndfValue::new_list(),
    }
}

/// Insert a value into an indexed container. Auto-detects Dict vs List.
/// For Dict: inserts with EndfKey::Int(idx). For List: grows the list to
/// accommodate `idx` (used as a direct positional index, no offset) and
/// sets `list[idx] = Some(value)`.
fn insert_indexed(container: &mut EndfValue, idx: i64, value: EndfValue) {
    match container {
        EndfValue::Dict(ref mut d) => {
            d.insert(EndfKey::Int(idx), value);
        }
        EndfValue::List(ref mut l) => {
            let uidx = idx as usize;
            while l.len() <= uidx { l.push(None); }
            l[uidx] = Some(value);
        }
        _ => {}
    }
}

/// Check if an indexed container has a value at `idx`. Auto-detects.
fn contains_indexed(container: &EndfValue, idx: i64) -> bool {
    match container {
        EndfValue::Dict(d) => d.contains_key(&EndfKey::Int(idx)),
        EndfValue::List(l) => {
            let uidx = idx as usize;
            uidx < l.len() && l[uidx].is_some()
        }
        _ => false,
    }
}

/// Get a mutable reference into an indexed container. Auto-detects.
fn get_indexed_mut(container: &mut EndfValue, idx: i64) -> Option<&mut EndfValue> {
    match container {
        EndfValue::Dict(ref mut d) => d.get_mut(&EndfKey::Int(idx)),
        EndfValue::List(ref mut l) => {
            let uidx = idx as usize;
            l.get_mut(uidx).and_then(|opt| opt.as_mut())
        }
        _ => None,
    }
}

/// Read from an indexed container (auto-detects Dict vs List).
/// Used on the write side where the container type tells us which
/// array_type mode was used at parse time.
fn get_indexed(container: &EndfValue, idx: i64) -> Option<&EndfValue> {
    match container {
        EndfValue::Dict(d) => d.get(&EndfKey::Int(idx)),
        EndfValue::List(l) => l.get(idx as usize).and_then(|opt| opt.as_ref()),
        _ => None,
    }
}

"#
    .to_string()
}

fn generate_dispatch_fn(recipes: &[(i32, i32, &[RecipeNode])]) -> String {
    let mut code = String::new();
    code.push_str(
        "/// Dispatch to the compiled parse function for the given MF/MT.\n\
         pub fn parse_section(\n    \
             mf: i32,\n    \
             mt: i32,\n    \
             lines: &[String],\n    \
             read_opts: &ReadOpts,\n    \
             parse_opts: &ParseOpts,\n\
         ) -> EndfResult<EndfValue> {\n    \
             match (mf, mt) {\n",
    );

    // Separate wildcard (mt == -1) from exact entries.
    let mut exact: Vec<(i32, i32)> = Vec::new();
    let mut wildcards: Vec<i32> = Vec::new();
    for &(mf, mt, _) in recipes {
        if mt == -1 {
            wildcards.push(mf);
        } else {
            exact.push((mf, mt));
        }
    }

    for (mf, mt) in &exact {
        let _ = writeln!(
            code,
            "        ({}, {}) => parse_mf{}_mt{}(lines, read_opts, parse_opts),",
            mf, mt, mf, mt
        );
    }
    for mf in &wildcards {
        let _ = writeln!(
            code,
            "        ({}, _) => parse_mf{}_wildcard(lines, read_opts, parse_opts),",
            mf, mf
        );
    }

    code.push_str(
        "        _ => Err(EndfError::RecipeParse {\n            \
             message: format!(\"no compiled parser for MF{}/MT{}\", mf, mt),\n        \
         }),\n    \
         }\n\
         }\n",
    );
    code
}

fn generate_write_dispatch_fn(recipes: &[(i32, i32, &[RecipeNode])]) -> String {
    let mut code = String::new();
    code.push_str(
        "/// Dispatch to the compiled write function for the given MF/MT.\n\
         pub fn write_section(\n    \
             mf: i32,\n    \
             mt: i32,\n    \
             data: &EndfValue,\n    \
             write_opts: &WriteOpts,\n\
         ) -> EndfResult<Vec<String>> {\n    \
             match (mf, mt) {\n",
    );

    let mut exact: Vec<(i32, i32)> = Vec::new();
    let mut wildcards: Vec<i32> = Vec::new();
    for &(mf, mt, _) in recipes {
        if mt == -1 {
            wildcards.push(mf);
        } else {
            exact.push((mf, mt));
        }
    }

    for (mf, mt) in &exact {
        let _ = writeln!(
            code,
            "        ({}, {}) => write_mf{}_mt{}(data, write_opts),",
            mf, mt, mf, mt
        );
    }
    for mf in &wildcards {
        let _ = writeln!(
            code,
            "        ({}, _) => write_mf{}_wildcard(data, write_opts),",
            mf, mf
        );
    }

    code.push_str(
        "        _ => Err(EndfError::RecipeParse {\n            \
             message: format!(\"no compiled writer for MF{}/MT{}\", mf, mt),\n        \
         }),\n    \
         }\n\
         }\n",
    );
    code
}

